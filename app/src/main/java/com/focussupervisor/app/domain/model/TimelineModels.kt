package com.focussupervisor.app.domain.model

/**
 * 领域层：监督时间线
 *
 * ===========================================================================
 * 这个文件解决什么问题
 * ===========================================================================
 * 「监督」这件事，如果只看当前状态（白名单里有什么、待办还没完成），
 * 监督者是没有判断依据的 —— 它不知道这些状态**是什么时候变成这样的**：
 *
 *  - 「小红书现在没被豁免」看不出他五分钟前刚被拦过三次；
 *  - 「待办没完成」看不出这项已经拖了三天；
 *  - 「上次对话是刚才」和「上次对话是三天前」需要完全不同的语气。
 *
 * 所以除了「现在是什么样」，还要记下「什么时候发生了什么」。[TimelineEvent]
 * 就是那条带时间的记录，它会被拼进提示词，构成 AI 的**时间感**。
 *
 * ===========================================================================
 * 为什么和对话记录分开
 * ===========================================================================
 * 对话（[ChatMessage]）本身就是一条时间线，而且已经有自己的淘汰策略（2000 条）
 * 和渲染方式。把「拦截、放行、修改消息」这些**事件**也塞进对话流，会有两个后果：
 *  1. 聊天记录被系统事件淹没，翻不到真正的对话；
 *  2. 每次往提示词里拼上下文都要先把两类东西从同一个列表里筛出来。
 *
 * 分开之后各司其职：对话回答「聊了什么」，时间线回答「发生了什么」。
 */

/**
 * 时间线上的一类事件。
 *
 * [label] 是给人看的中文短语，同时也会拼进提示词 —— 所以它必须是一句**能独立看懂**的
 * 短句，而不是一个需要额外解释的代号。
 */
enum class TimelineKind(val label: String) {

    /** 系统压制了一次没有豁免的应用。这是「抵抗」发生的地方，监督里最重要的一类事件。 */
    APP_BLOCKED("拦截未豁免应用"),

    /** 放行一次（AI 申请通过，或用户自己开的）。 */
    WHITELIST_GRANTED("放行应用"),

    /** 收回某次放行。 */
    WHITELIST_REVOKED("收回豁免"),

    /** 记下一项待办。 */
    TODO_ADDED("记下待办"),

    /** 完成一项待办。 */
    TODO_COMPLETED("完成待办"),

    /** 写入一条记忆。 */
    MEMORY_WRITTEN("写入记忆"),

    /** 一条短期记忆因为反复被召回而自动沉入长久层。 */
    MEMORY_PROMOTED("记忆沉入长久层"),

    /** 界面上手动触发的「强制锁定测试」。 */
    LOCK_TEST("强制锁定测试"),

    /**
     * 用户改动了一条已发出的消息。
     *
     * 记下来不是出于好奇：**事后修改说过的话**是一种典型的自我开脱行为，
     * 监督者知道「他说过这句，后来改成了那样」和只知道改后的版本，判断完全不同。
     */
    MESSAGE_EDITED("修改消息"),

    /** 用户删除了一条消息。理由同上。 */
    MESSAGE_DELETED("删除消息"),
}

/**
 * 时间线上的一条记录。
 *
 * @param id 稳定唯一标识，列表渲染做 key 用。
 * @param atMillis 事件发生的 Unix 毫秒时间戳。**这是整个模型的中心字段** ——
 *        每条记录必须带时间，没有时间的记录在这个模型里没有意义。
 * @param kind 事件类型，决定分类统计与图标。
 * @param title 一句话说清发生了什么（例如「小红书」「写周报」）。
 * @param detail 补充信息（例如「10 分钟 · 理由：回消息」），可以为空。
 */
data class TimelineEvent(
    val id: String,
    val atMillis: Long,
    val kind: TimelineKind,
    val title: String,
    val detail: String = "",
)

/**
 * 时间线的容量与拼进提示词时的取舍。
 */
object TimelineDefaults {

    /**
     * 持久化的条数上限。
     *
     * 300 条大致覆盖几周的日常使用。不做成「永久保留」有两个原因：DataStore 每次
     * 写入都要重写整份 JSON，记录是**高频**写入（每次拦截、每次放行都写一条），
     * 无上限会让每次写盘的代价随时间线性增长；而真正需要长期记住的东西，应该由
     * 记忆三层去承载 —— 时间线是「近期证据」，不是档案。
     */
    const val MAX_EVENTS = 300

    /**
     * 拼进提示词的条数上限。
     *
     * 比持久化上限小得多：上下文是稀缺资源，而「昨天的第十次拦截」对当下的判断
     * 几乎没有增量信息。给最近十几条，足以看出他这会儿在跟什么较劲。
     */
    const val PROMPT_EVENT_LIMIT = 14

    /**
     * 拼进提示词的时间窗口。
     *
     * 超过这个时长的事件只在「今天/昨天」的统计里出现，不再逐条列出：一周前的
     * 拦截记录对现在的对话没有指导意义，列出来只会稀释真正重要的近期事件。
     */
    const val PROMPT_HORIZON_HOURS = 48L
}
