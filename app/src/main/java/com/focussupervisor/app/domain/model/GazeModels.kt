package com.focussupervisor.app.domain.model

/**
 * 领域层：注视监控
 *
 * ===========================================================================
 * 它是什么
 * ===========================================================================
 * 用前置摄像头判断「用户此刻是不是在看这块屏幕」。它的价值不在于「监视」，
 * 而在于补上监督里最缺的那个事实：**他到底在不在**。
 *
 * 之前所有信号都是「他做了什么」（拦了哪个应用、说了什么话），但没有任何信号
 * 能回答「他现在是不是正看着屏幕」。于是会出现两种误差：
 *  - 人早走了，AI 还在对着一个空房间说话；
 *  - 人明明就盯着屏幕刷了两小时，记录里却只有几次拦截。
 *
 * 「正在注视」还有第二层用途：只有确认他在看，**截屏上传才有意义** ——
 * 否则就是拿一堆没人在看的画面去打扰视觉模型，既花钱又侵犯隐私。
 *
 * ===========================================================================
 * 隐私边界（写在模型里，不只是写在文档里）
 * ===========================================================================
 * 摄像头画面**只在设备本地处理**：ML Kit 的人脸检测跑在本地，帧用完即弃，
 * 不落盘、不上传。唯一可能离开设备的是「判定为正在注视」之后主动截图并上传的
 * 那一张，而且它由 [GazeConfig.uploadScreenshots] 单独控制、默认关闭。
 */

/**
 * 注视监控的运行状态。
 *
 * 用枚举而不是布尔量，是因为界面需要说清楚「为什么没有反应」：
 * 「未开启」和「画面里没有人」在用户看来是完全不同的两件事。
 */
enum class GazeState(val label: String) {

    /** 用户没开这个功能。 */
    OFF("未开启"),

    /** 正在申请摄像头、绑定分析器。 */
    STARTING("正在启动"),

    /** 摄像头开着，但画面里没有人脸。 */
    NO_FACE("画面里没有人"),

    /** 检测到人脸，但头部朝向说明他没在看屏幕。 */
    AWAY("人在，但没看屏幕"),

    /** 正在注视屏幕。 */
    LOOKING("正在注视屏幕"),

    /** 摄像头或模型出错。 */
    ERROR("出错了"),
}

/**
 * 注视监控的可调参数。
 *
 * 默认值都偏「保守」：宁可少记几次，也不要在用户只是路过屏幕时刷出一堆记录。
 *
 * @param enabled 总开关。关闭时前台服务不会去碰摄像头。
 * @param uploadScreenshots 判定为注视时，是否截屏并发给视觉模型。
 *        **默认关闭** —— 把屏幕内容发往外部端点是这个应用里最重的一个决定，
 *        必须由用户显式打开。
 * @param analyzeIntervalMillis 抽帧间隔。摄像头能跑 30fps，但判断「在不在看屏幕」
 *        每秒一帧都绰绰有余；降下来直接省电，也避免了持续发热。
 * @param lookHoldMillis 「连续注视多久」才算一次真正的注视。太短会把转头路过
 *        也算进去；1.5 秒足以滤掉大部分误判。
 * @param awayHoldMillis 「连续离开多久」才算离开。对称地去抖，避免视线在屏幕上
 *        扫一下就产生一次「离开 + 回来」。
 * @param captureCooldownMillis 两次截屏上传之间的最小间隔。这是花钱的那一项，
 *        必须有节流：默认 3 分钟，一天最多几百次，实际通常远低于此。
 * @param yawToleranceDegrees 头部左右转动的容许角（度）。正视屏幕时这个值接近 0，
 *        往左右看会迅速变大。
 * @param pitchToleranceDegrees 头部上下转动的容许角（度）。
 * @param eyeOpenThreshold 眼睛睁开的概率下限。低于它（闭眼、低头眯眼）不算注视。
 */
data class GazeConfig(
    val enabled: Boolean = false,
    val uploadScreenshots: Boolean = false,
    val analyzeIntervalMillis: Long = 700L,
    val lookHoldMillis: Long = 1_500L,
    val awayHoldMillis: Long = 1_500L,
    val captureCooldownMillis: Long = 3 * 60_000L,
    val yawToleranceDegrees: Float = 15f,
    val pitchToleranceDegrees: Float = 15f,
    val eyeOpenThreshold: Float = 0.3f,
)

/**
 * 当前视觉感知的完整状态。
 *
 * ===========================================================================
 * 为什么要多两个累计字段，而不是只报一个状态
 * ===========================================================================
 * 「此刻正在注视」是一个**瞬时**事实，它对监督几乎没有用 —— 用户看一眼手机就是
 * 一次注视，这件事本身不值得记录。真正有判断价值的是**持续了多久**：
 *
 *  - [continuousFocusMillis]：这一轮已经连续盯着看了多久。超过半小时意味着
 *    该提醒他休息，超过一小时意味着他可能卡在某个应用里出不来了；
 *  - [todayFocusMillis]：今天累计盯着屏幕多久。这是「今天过得怎么样」最直接的
 *    一个数字，也是 AI 在对话里最该引用的事实之一。
 *
 * 两者都是**运行期统计**，不落盘：进程重启会重新开始累计。这是刻意的取舍 ——
 * 精确到秒的跨重启统计需要一套后台计时与持久化，而它带来的判断增量很小；
 * 真正需要长期记住的是「他今天看了很久」这件事，而那个已经由时间线上的
 * 注视里程碑事件承担了。
 *
 * @param state 当前状态
 * @param continuousFocusMillis 本轮连续注视的时长；不在注视中时为 0
 * @param todayFocusMillis 本次运行以来累计的注视时长
 */
data class VisionStatus(
    val state: GazeState = GazeState.OFF,
    val continuousFocusMillis: Long = 0L,
    val todayFocusMillis: Long = 0L,
) {
    val isActive: Boolean get() = state != GazeState.OFF
}

/**
 * 注视监控的固定取舍。
 */object GazeDefaults {

    /**
     * 一次注视要持续这么久，才值得在时间线上留一条「放下手机」。
     *
     * 没有这个下限的话，用户每一次瞄一眼手机都会产生一对「在看 / 没在看」，
     * 一天就能把时间线上限（300 条）塞满，真正重要的事件反而被挤掉。
     */
    const val TIMELINE_MIN_SESSION_MILLIS = 30_000L

    /** 视觉模型返回的描述在时间线里的长度上限。 */
    const val MAX_DESCRIPTION_LENGTH = 200

    /** 抽帧间隔的下限，防止用户把一个参数调到把电池烧掉。 */
    const val MIN_ANALYZE_INTERVAL_MILLIS = 200L

    /**
     * 连续注视的提醒里程碑（分钟）。
     *
     * 连续盯屏幕 20 分钟就该有人提醒一次 —— 这是眼科和人体工学里最常被引用的那条线。
     * 之后每 15 分钟再提一次，间隔会越来越长但这不重要：重要的是**有人一直在数**。
     *
     * 每一个里程碑都会进时间线，并往会话流里发一条系统胶囊。
     */
    val FATIGUE_MILESTONE_MINUTES: List<Long> = listOf(20L, 30L, 45L, 60L, 90L, 120L)
}
