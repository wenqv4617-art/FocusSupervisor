package com.focussupervisor.app.core.vision

/**
 * 屏幕截图的提供者。
 *
 * ===========================================================================
 * 为什么需要这么一层
 * ===========================================================================
 * 截屏能力长在**无障碍服务**上（`AccessibilityService.takeScreenshot`，API 30+），
 * 而需要截图的动机长在**注视监控**上（前台服务里判定「他正在看屏幕」）。
 * 两个服务互不相识，也不该互相持有实例 —— 无障碍服务会被系统随时重建，
 * 前台服务的生命周期又比它长。
 *
 * 所以中间放一个极薄的注册点：无障碍服务在连接时把能力放进来，注视监控按需取用。
 * 这是一个**能力通道**，不是依赖注入，刻意保持最小。
 *
 * ===========================================================================
 * 拿不到截图时怎么办
 * ===========================================================================
 * `capture` 为 null 有三种正当原因，且都不是错误：
 *  - 无障碍服务没开（用户没给这个权限）；
 *  - 系统低于 Android 11（没有 `takeScreenshot`）；
 *  - 服务正在重建的瞬间。
 *
 * 这几种情况下注视监控仍然照常工作 —— 它照样记录「在看 / 没在看」，只是不发截图。
 * 功能降级而不是功能失效，这一点由调用方保证。
 */
object ScreenCaptureProvider {

    /**
     * 截取当前屏幕。成功返回 JPEG 字节，失败返回 null。
     *
     * 由 [com.focussupervisor.app.service.FocusAccessibilityService] 在
     * `onServiceConnected` 时注册、在 `onUnbind` / `onDestroy` 时清空。
     */
    @Volatile
    var capture: (suspend () -> ByteArray?)? = null

    /** 当前是否具备截屏能力。用于界面上解释「为什么没有截图」。 */
    val isAvailable: Boolean get() = capture != null
}
